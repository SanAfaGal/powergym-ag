create or replace function public.bot_membership_state(p_client_number bigint) returns jsonb
language plpgsql stable security definer set search_path = public, pg_temp as $$
declare
  v_sub public.subscriptions;
  v_plan public.plans;
begin
  select s.* into v_sub from public.subscriptions s
  where s.client_id = public.bot_client_id(p_client_number) and s.status <> 'canceled'
  order by s.end_date desc limit 1;
  if not found then
    return jsonb_build_object('estado', 'SIN_MEMBRESIA', 'fecha_fin', null);
  end if;
  select * into v_plan from public.plans where id = v_sub.plan_id;
  return jsonb_build_object(
    'estado', case when v_sub.end_date >= public.today_bogota() then 'ACTIVA' else 'VENCIDA' end,
    'tipo_membresia', public.bot_plan_name(v_plan),
    'fecha_inicio', v_sub.start_date,
    'fecha_fin', v_sub.end_date,
    'dias_restantes', v_sub.end_date - public.today_bogota()
  );
end;
$$;

create or replace function public.bot_expiring(p_days int default 3, p_as_of date default null) returns jsonb
language sql stable security definer set search_path = public, pg_temp as $$
  with ref as (select coalesce(p_as_of, public.today_bogota()) as d),
  latest as (
    select distinct on (s.client_id) s.client_id, s.plan_id, s.end_date
    from public.subscriptions s where s.status <> 'canceled'
    order by s.client_id, s.end_date desc
  )
  select coalesce(jsonb_agg(jsonb_build_object(
    'cliente_id', c.number, 'cliente_nombre', public.bot_full_name(c), 'telefono', c.phone,
    'membresia_id', null, 'fecha_fin', l.end_date, 'dias_restantes', l.end_date - ref.d,
    'tipo_membresia', public.bot_plan_name(p)
  ) order by l.end_date, c.number), '[]'::jsonb)
  from latest l
  join public.clients c on c.id = l.client_id and c.is_active
  join public.plans p on p.id = l.plan_id
  cross join ref
  where l.end_date between ref.d and ref.d + (p_days - 1)
$$;

-- saldo pendiente de suscripciones (lo mismo que el KPI "Deuda pendiente" del panel)
create or replace function public.bot_sub_balances()
returns table (client_id uuid, subscription_id uuid, plan_id uuid, balance numeric, since timestamptz)
language sql stable security definer set search_path = public, pg_temp as $$
  select s.client_id, s.id, s.plan_id, s.final_price - coalesce(p.paid, 0), s.created_at
  from public.subscriptions s
  left join (select subscription_id, sum(amount) as paid from public.payments group by subscription_id) p
    on p.subscription_id = s.id
  where s.status in ('active', 'pending_payment') and s.final_price - coalesce(p.paid, 0) > 0
$$;

create or replace function public.bot_client_balance(p_client_number bigint) returns numeric
language sql stable security definer set search_path = public, pg_temp as $$
  with c as (select public.bot_client_id(p_client_number) as id)
  select coalesce((select sum(d.amount) from public.debts d, c where d.client_id = c.id and d.status = 'pending'), 0)
       + coalesce((select sum(b.balance) from public.bot_sub_balances() b, c where b.client_id = c.id), 0)
$$;

create or replace function public.bot_debtors() returns jsonb
language sql stable security definer set search_path = public, pg_temp as $$
  with items as (
    select d.client_id, d.concept as concepto, d.amount as monto, d.created_at as fecha
    from public.debts d where d.status = 'pending'
    union all
    select b.client_id, 'Saldo de ' || initcap(pl.name), b.balance, b.since
    from public.bot_sub_balances() b join public.plans pl on pl.id = b.plan_id
  )
  select coalesce(jsonb_agg(x order by x->>'cliente_nombre'), '[]'::jsonb) from (
    select jsonb_build_object(
      'cliente_id', c.number, 'cliente_nombre', public.bot_full_name(c),
      'total_debe', sum(i.monto),
      'detalle', jsonb_agg(jsonb_build_object('concepto', i.concepto, 'monto', i.monto, 'fecha', i.fecha) order by i.fecha)
    ) as x
    from items i join public.clients c on c.id = i.client_id
    group by c.id
  ) t
$$;

create or replace function public.bot_client_payments(p_client_number bigint, p_date date default null) returns jsonb
language sql stable security definer set search_path = public, pg_temp as $$
  with c as (select public.bot_client_id(p_client_number) as id),
  rows as (
    select p.number, p.payment_date as at, p.amount, p.payment_method, 'GYM' as tipo,
           public.bot_plan_name(pl) as concepto
    from public.payments p
    join public.subscriptions s on s.id = p.subscription_id
    join public.plans pl on pl.id = s.plan_id, c
    where s.client_id = c.id
    union all
    select ps.number, ps.sold_at, ps.amount, ps.payment_method, 'PRODUCTO', coalesce(pr.name, ps.description)
    from public.product_sales ps left join public.products pr on pr.id = ps.product_id, c
    where ps.client_id = c.id and ps.voided_at is null
  )
  select coalesce(jsonb_agg(jsonb_build_object(
    'pago_id', r.number,
    'fecha', (r.at at time zone 'America/Bogota')::date,
    'monto_total', r.amount::text,
    'metodo_pago', public.bot_method_name(r.payment_method),
    'estado', 'CONFIRMADO',
    'lineas', jsonb_build_array(jsonb_build_object('tipo', r.tipo, 'monto', r.amount::text, 'concepto', r.concepto))
  ) order by r.at desc), '[]'::jsonb)
  from rows r
  where p_date is null or (r.at at time zone 'America/Bogota')::date = p_date
$$;

create or replace function public.bot_daily_close(p_date date default null) returns jsonb
language sql stable security definer set search_path = public, pg_temp as $$
  with d as (select coalesce(p_date, public.today_bogota()) as day),
  rows as (
    select p.amount, p.payment_method, 'GYM' as tipo
    from public.payments p, d where (p.payment_date at time zone 'America/Bogota')::date = d.day
    union all
    select ps.amount, ps.payment_method, 'PRODUCTO'
    from public.product_sales ps, d
    where ps.voided_at is null and (ps.sold_at at time zone 'America/Bogota')::date = d.day
  )
  select jsonb_build_object(
    'fecha', (select day from d),
    'total_general', coalesce((select sum(amount) from rows), 0),
    'por_metodo_pago', coalesce((select jsonb_object_agg(m, t) from (
        select public.bot_method_name(payment_method) as m, sum(amount) as t from rows group by 1) x), '{}'::jsonb),
    'por_categoria', coalesce((select jsonb_object_agg(tipo, t) from (
        select tipo, sum(amount) as t from rows group by 1) y), '{}'::jsonb),
    'cantidad_pagos', (select count(*) from rows),
    'pendientes_de_aclaracion', 0
  )
$$;

