-- supabase/migrations/00000000000055_bot_api.sql
--
-- API para el bot de WhatsApp: funciones que el bot llama con la service key y que devuelven
-- los datos con la misma forma que ya usa el agente (números cortos, EFECTIVO/TRANSFERENCIA,
-- ACTIVA/VENCIDA...). Así la lógica del bot no cambia y toda la regla de negocio vive en SQL,
-- donde se prueba con pgTAP.
--
-- Números cortos: el agente trabaja con ids enteros (cliente 12, plan 1), no con UUID. Cada
-- tabla que el bot nombra recibe una columna `number`.

alter table public.clients  add column number bigint generated by default as identity unique;
alter table public.plans    add column number bigint generated by default as identity unique;
alter table public.products add column number bigint generated by default as identity unique;
alter table public.debts    add column number bigint generated by default as identity unique;

-- ============================================================
-- Helpers (solo los usa el resto de funciones)
-- ============================================================
create or replace function public.bot_method(p text) returns text
language sql immutable set search_path = public, pg_temp as $$
  select case when upper(trim(p)) in ('EFECTIVO', 'CASH') then 'cash' else 'bank' end
$$;

create or replace function public.bot_method_name(p text) returns text
language sql immutable set search_path = public, pg_temp as $$
  select case p when 'cash' then 'EFECTIVO' else 'TRANSFERENCIA' end
$$;

-- nombre con el que el agente conoce a un plan: su slug en mayúsculas (MENSUALIDAD, QUINCENA...)
create or replace function public.bot_plan_name(p public.plans) returns text
language sql immutable set search_path = public, pg_temp as $$
  select upper(coalesce(nullif(p.slug, ''), p.name))
$$;

create or replace function public.bot_full_name(c public.clients) returns text
language sql immutable set search_path = public, pg_temp as $$
  select trim(c.first_name || ' ' || coalesce(c.last_name, ''))
$$;

create or replace function public.bot_client_id(p_number bigint) returns uuid
language sql stable set search_path = public, pg_temp as $$
  select id from public.clients where number = p_number
$$;

