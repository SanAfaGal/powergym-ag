create or replace function public.bot_entry_info(p_number bigint) returns jsonb
language sql stable security definer set search_path = public, pg_temp as $$
  select coalesce(
    (select jsonb_build_object('kind', 'payment', 'number', p.number, 'reported_by', p.reported_by,
        'amount', p.amount, 'client_name', public.bot_full_name(c), 'voided', false)
     from public.payments p join public.subscriptions s on s.id = p.subscription_id
     join public.clients c on c.id = s.client_id where p.number = p_number),
    (select jsonb_build_object('kind', 'product_sale', 'number', ps.number, 'reported_by', ps.reported_by,
        'amount', ps.amount, 'client_name', (select public.bot_full_name(c) from public.clients c where c.id = ps.client_id),
        'voided', ps.voided_at is not null)
     from public.product_sales ps where ps.number = p_number),
    (select jsonb_build_object('kind', 'payment', 'number', v.number, 'reported_by', v.reported_by,
        'amount', v.amount, 'client_name', public.bot_full_name(c), 'voided', true)
     from public.voided_payments v join public.subscriptions s on s.id = v.subscription_id
     join public.clients c on c.id = s.client_id where v.number = p_number)
  )
$$;

create or replace function public.bot_void(p_number bigint, p_voided_by text, p_reason text default null) returns jsonb
language plpgsql security definer set search_path = public, pg_temp as $$
declare
  v_info jsonb := public.bot_entry_info(p_number);
  v_res jsonb;
begin
  -- esta función solo la puede llamar la service key y el bot ya comprobó quién pide anular:
  -- se marca la llamada como service_role (solo dura esta transacción) para pasar la regla
  -- de permisos de void_payment, pensada para el panel.
  perform set_config('request.jwt.claim.role', 'service_role', true);
  v_res := public.void_entry(p_number, p_voided_by, p_reason);
  insert into public.events (type, client_id, reported_by, original_message, payment_number, status, data)
  values ('PAGO_ANULADO',
          public.bot_client_id(null), p_voided_by, p_reason, p_number, 'CONFIRMADO',
          jsonb_build_object('monto', v_info->>'amount', 'cliente', v_info->>'client_name',
            'reportado_por_original', v_info->>'reported_by',
            'membresias_canceladas', case when (v_res->>'subscription_canceled')::boolean then 1 else 0 end,
            'membresias_posteriores', coalesce((v_res->>'later_subscriptions')::boolean, false)));
  return v_res || jsonb_build_object('client_name', v_info->>'client_name', 'reported_by', v_info->>'reported_by');
end;
$$;

create or replace function public.bot_day_report(p_date date default null) returns jsonb
language sql stable security definer set search_path = public, pg_temp as $$
  with d as (select coalesce(p_date, public.today_bogota()) as day)
  select jsonb_build_object(
    'close', public.bot_daily_close((select day from d)),
    'pagos', coalesce((select jsonb_agg(jsonb_build_object(
        'number', r.number, 'hora', to_char(r.at at time zone 'America/Bogota', 'HH24:MI'),
        'cliente', r.cliente, 'concepto', r.concepto, 'monto', r.amount,
        'metodo', public.bot_method_name(r.payment_method), 'reportado_por', r.reported_by) order by r.at)
      from (
        select p.number, p.payment_date as at, public.bot_full_name(c) as cliente, public.bot_plan_name(pl) as concepto,
               p.amount, p.payment_method, p.reported_by
        from public.payments p join public.subscriptions s on s.id = p.subscription_id
        join public.clients c on c.id = s.client_id join public.plans pl on pl.id = s.plan_id
        where (p.payment_date at time zone 'America/Bogota')::date = (select day from d)
        union all
        select ps.number, ps.sold_at, coalesce((select public.bot_full_name(c) from public.clients c where c.id = ps.client_id), 'Sin cliente'),
               coalesce(pr.name, ps.description), ps.amount, ps.payment_method, ps.reported_by
        from public.product_sales ps left join public.products pr on pr.id = ps.product_id
        where ps.voided_at is null and (ps.sold_at at time zone 'America/Bogota')::date = (select day from d)
      ) r), '[]'::jsonb),
    'anulados', coalesce((select jsonb_agg(jsonb_build_object(
        'number', e.payment_number, 'cliente', e.data->>'cliente', 'monto', e.data->>'monto',
        'anulado_por', e.reported_by) order by e.created_at)
      from public.events e where e.type = 'PAGO_ANULADO'
        and (e.created_at at time zone 'America/Bogota')::date = (select day from d)), '[]'::jsonb),
    'deudas_nuevas', coalesce((select jsonb_agg(x) from (
        select jsonb_build_object('cliente', public.bot_full_name(c), 'monto', db.amount, 'concepto', db.concept) as x
        from public.debts db join public.clients c on c.id = db.client_id
        where db.status <> 'voided' and (db.created_at at time zone 'America/Bogota')::date = (select day from d)
        union all
        select jsonb_build_object('cliente', public.bot_full_name(c), 'monto', b.balance,
                                  'concepto', 'Saldo pendiente de pago parcial')
        from public.bot_sub_balances() b join public.clients c on c.id = b.client_id
        where (b.since at time zone 'America/Bogota')::date = (select day from d)
          and exists (select 1 from public.payments p where p.subscription_id = b.subscription_id)
      ) q), '[]'::jsonb)
  )
$$;

-- ============================================================
-- Solo la service key (el bot) puede llamar estas funciones
-- ============================================================
do $$
declare r record;
begin
  for r in select p.oid::regprocedure as sig from pg_proc p join pg_namespace n on n.oid = p.pronamespace
           where n.nspname = 'public' and p.proname like 'bot\_%'
  loop
    execute format('revoke execute on function %s from public, anon, authenticated', r.sig);
    execute format('grant execute on function %s to service_role', r.sig);
  end loop;
end $$;
